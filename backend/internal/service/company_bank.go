func BuildCompanyQuestionBank(companyName string) string {
	name := strings.TrimSpace(companyName)
	if name == "" {
		return "未指定公司，按通用技术面试标准出题。"
	}

	if prompt, ok := companyQuestionBankMap[name]; ok {
		return prompt
	}

	return "该公司没有内置题库画像，请结合岗位信息、简历经历与近年互联网公司技术面常见风格，给出贴近该公司的真实中文面试题。"
}
